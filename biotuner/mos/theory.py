"""Number theory of moment-of-symmetry (well-formed) scales.

This module is deliberately dependency-free -- it imports nothing but the
standard library, so its correctness can be checked in isolation from the
rest of biotuner.  Everything here works on exact :class:`~fractions.Fraction`
arithmetic; no floating-point comparison decides a combinatorial fact.

The central object of study is the **generator fraction**

.. math::  g = \\log(\\text{generator}) / \\log(\\text{period}) \\in (0, 1)

i.e. the size of the generator expressed as a fraction of the period
(the "generator/period tuning ratio" of Milne et al., 2011).  A generator of
702 cents against a 1200-cent period gives :math:`g = 0.585`.

The key fact, due to the three-distance theorem and exploited throughout
Milne et al. §3, is that stacking a generator produces a scale with exactly
two step sizes **precisely** at the cardinalities that appear as denominators
along the Stern-Brocot path toward :math:`g`.  So the entire MOS series of a
generator is obtained by walking the tree -- no brute-force search over
cardinalities is needed.

References
----------
Milne, A.J., Carlé, M., Sethares, W.A., Noll, T., Holland, S. (2011).
Scratching the Scale Labyrinth. In *Mathematics and Computation in Music*,
LNAI 6726, 180--195. https://doi.org/10.1007/978-3-642-21590-2_14

Carey, N., Clampitt, D. (1989). Aspects of Well-formed Scales.
*Music Theory Spectrum* 11, 187--206.
"""

