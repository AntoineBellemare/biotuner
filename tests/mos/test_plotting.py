@pytest.mark.parametrize("n", [1, 2, 3, 4, 6])
def test_fractional_period_shows_only_multiples_of_n(n):
    """A scale with n periods per octave repeats n times, so a ring can only
    hold a note count divisible by n."""
    fig, ax = P.plot_labyrinth(24, periods_per_octave=n)
    radii = set()
    for line in ax.get_lines():
        radii.update(np.round(line.get_ydata(), 6))
    rings = sorted(r for r in radii if 0 < r <= 24)
    assert rings, "no rings drawn"
    assert all(int(round(r)) % n == 0 for r in rings)


def test_fractional_period_has_n_fold_rotational_symmetry():
    """Every arc appears once per period, at a fixed angular offset."""
    n = 3
    fig, ax = P.plot_labyrinth(24, periods_per_octave=n)
    inner = [ln for ln in ax.get_lines()
             if len(ln.get_ydata()) > 8 and abs(ln.get_ydata()[0] - 6.0) < 1e-9]
    starts = sorted(float(ln.get_xdata()[0]) % (2 * math.pi) for ln in inner)
    assert len(starts) % n == 0
    # Rotating the whole set by one period maps it onto itself.
    shifted = sorted((s + 2 * math.pi / n) % (2 * math.pi) for s in starts)
    assert np.allclose(starts, shifted, atol=1e-6)


