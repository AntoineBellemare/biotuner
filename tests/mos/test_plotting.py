def test_step_covariation_crosses_at_the_equalized_landmark():
    fig, axes = P.plot_step_covariation(5, 2)
    top = axes[0]
    large, small = top.get_lines()[0], top.get_lines()[1]
    xl, yl = large.get_xdata(), large.get_ydata()
    ys = small.get_ydata()
    eq = float(T.mos_landmarks(5, 2).equalized) * 1200
    i = int(np.argmin(np.abs(xl - eq)))
    assert yl[i] == pytest.approx(ys[i], abs=1.0)

    # The plot deliberately spans the MOS *and* its inverse, meeting at the
    # equalized landmark, so the tiling identity swaps counts across it:
    # 5L + 2s above, 2L + 5s below.
    above, below = xl > eq, xl < eq
    assert np.allclose(5 * yl[above] + 2 * ys[above], 1200.0, atol=1e-6)
    assert np.allclose(2 * yl[below] + 5 * ys[below], 1200.0, atol=1e-6)


