def test_ji_landscape_finds_the_known_optimum_for_twelve_notes():
    """12 notes approximate 5-limit best near a 702-cent generator."""
    targets = P.JI_5_LIMIT
    tpos = np.mod(np.log2(np.asarray(targets)), 1.0)
    best_err, best_g = 1e9, None
    for g in np.linspace(0.5, 1.0, 4001)[1:-1]:
        cards = [c for c, _, _ in T.mos_series(g, 12, include_trivial=True)]
        if 12 not in cards:
            continue
        deg = np.asarray(T.degrees_from_generator(float(g), 12))
        d = np.abs(tpos[:, None] - deg[None, :])
        d = np.minimum(d, 1 - d)
        err = float(d.min(axis=1).mean() * 1200)
        if err < best_err:
            best_err, best_g = err, g
    assert best_g * 1200 == pytest.approx(701.7, abs=2.0)
    assert best_err == pytest.approx(8.4, abs=0.5)


