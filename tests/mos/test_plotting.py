def test_labyrinth_draws_every_ring():
    fig, ax = P.plot_labyrinth(12)
    assert ax.name == "polar"
    assert ax.get_ylim()[1] > 12
    # Every MOS cardinality from 2 to 12 must appear as a radius somewhere.
    radii = set()
    for line in ax.get_lines():
        radii.update(np.round(line.get_ydata(), 6))
    for card in range(2, 13):
        assert float(card) in radii, f"ring {card} missing"


def test_labyrinth_is_left_right_symmetric():
    """Milne et al. section 4: 'the structure is left-right symmetric, because a
    scale created using any generator is identical to the scale generated by the
    complement of the generator'."""
    nodes = T.sb_tree_nodes(14)
    values = {float(n.node) for n in nodes}
    for v in values:
        assert any(abs((1.0 - v) - w) < 1e-12 for w in values)


def test_spokes_stop_on_their_own_ring():
    """'For each spoke, there is some circle that the spoke touches but does not
    cross. This circle gives the number of notes in the corresponding equal step
    scale.'"""
    for node in T.sb_tree_nodes(14):
        assert node.cardinality == node.node.denominator


