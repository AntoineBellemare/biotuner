def _eeg_readings(**kwargs):
    kwargs.setdefault("include_ratios", False)     # raw Hz: 19.31 is no interval
    kwargs.setdefault("min_cardinality", 5)
    kwargs.setdefault("max_cardinality", 9)
    return forward_scales(EEG_PEAKS, **kwargs)[:6]


def _forward_scatter(ax):
    return ax.collections[-1]


def _stars(ax):
    return [ln for ln in ax.get_lines() if ln.get_marker() == "*"]


def test_forward_vs_inverse_plots_one_point_per_reading():
    readings = _eeg_readings()
    fig, ax = P.plot_forward_vs_inverse(readings, best_mos(EEG_PEAKS,
                                                           max_cardinality=9))
    assert ax.name == "polar"
    offsets = _forward_scatter(ax).get_offsets()
    assert len(offsets) == len(readings)
    # Angle is the generator, radius the cardinality -- the labyrinth's own axes.
    drawn = {(round(float(t) / (2 * math.pi), 9), int(round(r)))
             for t, r in offsets}
    expected = {(round(P._bright(r.scale.generator), 9), r.scale.cardinality)
                for r in readings}
    assert drawn == expected


def test_forward_vs_inverse_marks_the_two_directions_apart():
    """The figure exists to tell an observed generator from a latent one, so
    the two must not be drawn as the same kind of thing."""
    readings = _eeg_readings()
    inverse = best_mos(EEG_PEAKS, max_cardinality=9)
    fig, ax = P.plot_forward_vs_inverse(readings, inverse)

    stars = _stars(ax)
    assert len(stars) == 1, "exactly one inverse fit, and only it is a star"
    star = stars[0]
    assert star.get_markeredgecolor() == P.INVERSE_COLOR
    # Open, so a forward reading landing on the same spot still shows through.
    assert str(star.get_markerfacecolor()).lower() == "none"
    assert star.get_ydata()[0] == inverse.scale.cardinality
    assert star.get_xdata()[0] == pytest.approx(
        2 * math.pi * P._bright(inverse.scale.generator)
    )

    # The inverse fit is not smuggled into the forward scatter, and no forward
    # marker can borrow its colour: the ramp and the flag are disjoint.
    scatter = _forward_scatter(ax)
    assert len(scatter.get_offsets()) == len(readings)
    shades = scatter.get_cmap()(scatter.norm(scatter.get_array()))
    assert not any(np.allclose(shade, to_rgba(P.INVERSE_COLOR), atol=0.05)
                   for shade in shades)

    labels = [t.get_text() for t in ax.get_legend().get_texts()]
    assert sum("inverse fit" in label for label in labels) == 1
    assert len(labels) > 1, "the forward readings need their own key"


def test_forward_vs_inverse_sizes_points_by_corroboration():
    """A stack of fifths states the fifth twice -- 3/2, and 27/16 over 9/8 --
    so that generator is better attested than the ones seen once."""
    readings = forward_scales([1.0, 1.125, 1.265625, 1.5], max_cardinality=12)
    readings = sorted(readings, key=lambda r: r._rank_key)[:8]
    counts = [r.n_sources for r in readings]
    assert len(set(counts)) > 1, "fixture must exercise the size encoding"

    fig, ax = P.plot_forward_vs_inverse(readings)
    sizes = _forward_scatter(ax).get_sizes()
    assert sizes[counts.index(max(counts))] > sizes[counts.index(min(counts))]


def test_forward_vs_inverse_draws_the_bright_half_only():
    """Neither direction can report the dark spelling, and a permanently empty
    half-circle would read as absence of evidence."""
    fig, ax = P.plot_forward_vs_inverse(_eeg_readings())
    assert ax.get_thetamin() == pytest.approx(180.0)
    assert ax.get_thetamax() == pytest.approx(360.0)
    thetas = [float(t) for t, _ in _forward_scatter(ax).get_offsets()]
    thetas.append(float(_stars(ax)[0].get_xdata()[0]))
    assert all(math.pi <= t <= 2 * math.pi + 1e-9 for t in thetas)


def test_forward_vs_inverse_captions_the_generator_it_drew():
    """A fit is free to name either spelling of its own scale.  The star goes to
    the bright one, so the caption has to as well."""
    fit = best_mos(EEG_PEAKS, max_cardinality=9)
    bright = P._bright(fit.scale.generator)
    dark = MOSScale(fit.scale.n_large, fit.scale.n_small, 1.0 - bright,
                    fit.scale.period, validate=False)
    fig, ax = P.plot_forward_vs_inverse(_eeg_readings(), replace(fit, scale=dark))

    assert _stars(ax)[0].get_xdata()[0] == pytest.approx(2 * math.pi * bright)
    assert f"{bright * 1200:.1f} c" in ax.get_title()
    assert f"{(1 - bright) * 1200:.1f} c" not in ax.get_title()


def test_forward_vs_inverse_keys_each_generator_once():
    readings = _eeg_readings()
    fig, ax = P.plot_forward_vs_inverse(readings)
    n_generators = len({round(P._bright(r.scale.generator), 9) for r in readings})
    tags = sorted(t.get_text() for t in ax.texts)
    assert tags == sorted(P._tag_label(i) for i in range(n_generators))
    labels = [t.get_text() for t in ax.get_legend().get_texts()]
    assert sum(any(label.startswith(tag) for tag in tags) for label in labels) \
        == n_generators


